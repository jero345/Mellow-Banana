-- Mellow & Banana — CMS schema.
--
-- Run once in the Supabase SQL editor (or `psql`) on a fresh project.
-- Everything is public-read (it is a public website) and writable only by
-- users listed in `public.admins`. Bilingual fields are { "es": "", "en": "" }.
--
-- New projects no longer expose tables to the Data API automatically, so the
-- GRANTs below are required, and RLS is on for every table.

-- ─────────────────────────────── Admins ───────────────────────────────

create table public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.admins enable row level security;

-- An admin can see their own row; that is what the write policies below test.
create policy "admins read own row" on public.admins
  for select to authenticated
  using ((select auth.uid()) = user_id);
-- Write policies test membership with a plain subquery on this table, run as
-- the caller — so no SECURITY DEFINER helper is needed.

-- ─────────────────────────────── Content ──────────────────────────────

/** Site-wide settings: contact, socials, tags, studio photos, hero media. One row. */
create table public.settings (
  id smallint primary key default 1 check (id = 1),
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

/** Every UI string, by dictionary key. */
create table public.translations (
  key text primary key,
  es text not null default '',
  en text not null default '',
  updated_at timestamptz not null default now()
);

create table public.projects (
  slug text primary key check (slug ~ '^[a-z0-9-]+$'),
  position int not null default 0,
  published boolean not null default true,
  featured boolean not null default false,
  year int,
  industry text,
  categories text[] not null default '{}',
  client jsonb not null default '{}'::jsonb,
  short_title jsonb not null default '{}'::jsonb,
  tagline jsonb not null default '{}'::jsonb,
  sector jsonb not null default '{}'::jsonb,
  cover text,
  cover_alt jsonb not null default '{}'::jsonb,
  intro jsonb not null default '[]'::jsonb,
  blocks jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);

create table public.clients (
  id bigint generated by default as identity primary key,
  position int not null default 0,
  name text not null,
  logo text not null
);

create table public.industries (
  key text primary key,
  position int not null default 0,
  label jsonb not null default '{}'::jsonb
);

create table public.services (
  key text primary key,
  position int not null default 0,
  title jsonb not null default '{}'::jsonb,
  lead jsonb not null default '{}'::jsonb,
  items jsonb not null default '[]'::jsonb
);

/** "Cómo lo hacemos" on the About page. */
create table public.pillars (
  key text primary key,
  position int not null default 0,
  title jsonb not null default '{}'::jsonb,
  body jsonb not null default '{}'::jsonb,
  images text[] not null default '{}'
);

-- ───────────────────────────── Access rules ───────────────────────────

do $$
declare
  t text;
begin
  foreach t in array array['settings', 'translations', 'projects', 'clients', 'industries', 'services', 'pillars']
  loop
    execute format('alter table public.%I enable row level security', t);

    -- Some projects grant everything to these roles by default; start from nothing.
    execute format('revoke all on public.%I from anon, authenticated', t);

    execute format('grant select on public.%I to anon, authenticated', t);
    execute format('grant insert, update, delete on public.%I to authenticated', t);

    execute format(
      'create policy "public read" on public.%I for select to anon, authenticated using (true)', t);

    execute format(
      'create policy "admins insert" on public.%I for insert to authenticated
         with check (exists (select 1 from public.admins a where a.user_id = (select auth.uid())))', t);

    execute format(
      'create policy "admins update" on public.%I for update to authenticated
         using (exists (select 1 from public.admins a where a.user_id = (select auth.uid())))
         with check (exists (select 1 from public.admins a where a.user_id = (select auth.uid())))', t);

    execute format(
      'create policy "admins delete" on public.%I for delete to authenticated
         using (exists (select 1 from public.admins a where a.user_id = (select auth.uid())))', t);
  end loop;
end $$;

revoke all on public.admins from anon, authenticated;
grant select on public.admins to authenticated;

-- Unpublished projects stay out of the public site but remain visible to admins.
-- Two policies, not one with an OR: `anon` cannot read `admins`, so a policy
-- that mentions it would make every anonymous read fail.
drop policy "public read" on public.projects;
create policy "public read" on public.projects
  for select to anon, authenticated
  using (published);
create policy "admins read drafts" on public.projects
  for select to authenticated
  using (exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

-- ─────────────────────────────── Storage ──────────────────────────────

insert into storage.buckets (id, name, public)
values ('media', 'media', true)
on conflict (id) do nothing;

-- Public bucket: files are readable by URL. Admins upload, replace and delete
-- (upsert needs insert + select + update).
create policy "media admin select" on storage.objects
  for select to authenticated
  using (bucket_id = 'media' and exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

create policy "media admin insert" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'media' and exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

create policy "media admin update" on storage.objects
  for update to authenticated
  using (bucket_id = 'media' and exists (select 1 from public.admins a where a.user_id = (select auth.uid())))
  with check (bucket_id = 'media' and exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

create policy "media admin delete" on storage.objects
  for delete to authenticated
  using (bucket_id = 'media' and exists (select 1 from public.admins a where a.user_id = (select auth.uid())));
